def _python_stub(src_file: str, pr_number: Optional[int]) -> tuple[str, str]:
    path = Path(src_file.replace("\\", "/"))
    stem = path.stem

    parts = path.parts
    start = 1 if parts and parts[0] in _SRC_ROOTS else 0
    dir_parts = parts[start:-1]

    test_dir = "tests/" + "/".join(dir_parts) if dir_parts else "tests"
    test_path = f"{test_dir}/test_{stem}.py"

    module_path = ".".join(list(dir_parts) + [stem]) if dir_parts else stem
    pr_note = f" on PR #{pr_number}" if pr_number else ""

    content = f"""import pytest
# auto-generated by quality-orchestrator
# target: {src_file}{pr_note}
from {module_path} import *  # noqa: F401,F403


def test_{stem}_happy_path():
    # TODO: replace with real assertion
    pass


@pytest.mark.skip(reason="TODO: implement invalid input test")
def test_{stem}_invalid_input():
    pass


# TODO: add edge cases based on diff
"""
    return test_path, content
