from pathlib import Path
from typing import Optional

from engine.mapping import _SRC_ROOTS, detect_js_runner

_VALID_FRAMEWORKS = {"auto", "pytest", "playwright", "vitest", "jest"}


def generate_stub(
    src_file: str,
    pr_number: Optional[int] = None,
    framework: str = "auto",
) -> tuple[str, str]:
    """Return (test_path, stub_content) for a source file with no coverage.

    framework: "auto" detects from config files and file extension; explicit values
    force a specific framework (pytest, playwright, vitest, jest).
    """
    if framework not in _VALID_FRAMEWORKS:
        raise ValueError(f"Unknown framework '{framework}'. Valid options: {', '.join(sorted(_VALID_FRAMEWORKS))}")
    if framework == "pytest":
        return _python_stub(src_file, pr_number)
    if framework == "playwright":
        return _playwright_stub(src_file, pr_number)
    if framework == "vitest":
        return _vitest_stub(src_file, pr_number)
    if framework == "jest":
        return _jest_stub(src_file, pr_number)
    # auto: detect from extension, then runner config
    ext = Path(src_file).suffix.lower().lstrip(".")
    if ext == "py":
        return _python_stub(src_file, pr_number)
    runner = detect_js_runner()
    if runner == "playwright":
        return _playwright_stub(src_file, pr_number)
    if runner == "jest":
        return _jest_stub(src_file, pr_number)
    return _vitest_stub(src_file, pr_number)


def _playwright_stub(src_file: str, pr_number: Optional[int]) -> tuple[str, str]:
    path = Path(src_file.replace("\\", "/"))
    stem = path.stem
    suffix = path.suffix  # includes the dot

    parts = path.parts
    start = 1 if parts and parts[0] in _SRC_ROOTS else 0
    dir_parts = parts[start:-1]

    test_dir = "tests/" + "/".join(dir_parts) if dir_parts else "tests"
    test_path = f"{test_dir}/{stem}.spec{suffix}"
    import_path = "../" * (test_path.count("/")) + src_file

    pr_note = f" on PR #{pr_number}" if pr_number else ""
    content = f"""import {{ test, expect }} from '@playwright/test';
import {{ {stem} }} from '{import_path}';

// auto-generated by quality-orchestrator
// target: {src_file}{pr_note}

test.describe('{stem}', () => {{

  test('happy path', async () => {{
    // TODO: replace with real assertion
    const result = await {stem}(/* args */);
    expect(result).toBeDefined();
  }});

  test('handles invalid input', async () => {{
    await expect(
      {stem}(null)
    ).rejects.toThrow();
  }});

  test.todo('edge cases — fill in based on diff');
}});
"""
    return test_path, content


